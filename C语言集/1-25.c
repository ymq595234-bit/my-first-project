/* 1-25 用连乘公式求 π
 * 输入：项数 n
 * 输出：π 的近似值，保留 7 位小数
 * 公式（沃利斯型）：π = 2 × Π [ (4i²) / ((2i-1)(2i+1)) ]，i 从 1 到 n
 */
#include <stdio.h>

int main(){
    int n, i;
    double pi = 1.0;

    scanf("%d", &n);

    for (i = 1; i <= n; i++){
        pi *= (4.0 * i * i) / ((2.0 * i - 1) * (2.0 * i + 1));
    }

    printf("%.7f", pi * 2);      /* 连乘得到的是 π/2，所以最后乘 2 */

    return 0;
}
