/* 1-23 按公式求值
 * 输入：整数 n
 * 输出：n * (n + 1) * (2n + 4) / 12 的结果
 * 说明：2n+4 = 2(n+2)，所以整个式子等于 n(n+1)(n+2)/6；
 *       三个连续整数相乘一定能被 6 整除，因此结果必然是整数，
 *       先乘后除不会丢精度。
 * 优化：原代码用 sum、x 两个中间变量绕了一圈，直接算成一行更清楚。
 */
#include <stdio.h>

int main(){
    int n, result;

    scanf("%d", &n);
    result = n * (n + 1) * (2 * n + 4) / 12;
    printf("%d", result);

    return 0;
}
