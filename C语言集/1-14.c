/* 1-14 判断两个整数是否相等
 * 输入：两个整数 x y
 * 输出：比较结论"它们相等。" / "它们不相等。"
 * 已修正两处：
 *   1) 提示语原本写在 scanf 之后，屏幕上会先出结果再出提示 —— 已移到前面；
 *   2) printf(x == y ? ...) 是把字符串直接当格式串用，不规范 ——
 *      改成 printf("%s", x == y ? ...)，更安全。
 */
#include <stdio.h>

int main(){
    int x, y;

    printf("请输入两个整数。\n");
    printf("整数1：");
    printf("整数2：");
    scanf("%d %d", &x, &y);

    printf("%s", x == y ? "它们相等。\n" : "它们不相等。\n");   /* 三目运算符：条件 ? 真 : 假 */

    return 0;
}
