/* 2-6 以 9999 结束，倒序输出
 * 输入：一串整数，最后一个 9999 是结束标志（可以不在同一行）
 * 输出：把 9999 之前的数倒着输出，数字之间一个空格，最后一个后面不加
 * 思路：边读边存；读到 9999 立刻 break，所以它进不了数组。
 * 关键：i 读完就是总个数，所以倒序循环写 i = i - 1。
 *       最后一个数后面不加空格靠 if (i > 0) 保证。
 */
#include <stdio.h>

int main()
{
    int a[100];
    int i = 0;
    int x;

    while (1) {
        scanf("%d", &x);

        if (x == 9999) {
            break;
        }

        a[i] = x;
        i++;
    }

    for (i = i - 1; i >= 0; i--) {
        printf("%d", a[i]);

        if (i > 0) {
            printf(" ");
        }
    }

    return 0;
}
